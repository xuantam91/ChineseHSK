export const CURATED_MEDIA_RESOURCES: CuratedMediaItem[] = RAW_MEDIA_DATA.map((item) => ({
  ...item,
  sanitizedInfo: sanitizeMediaResource(item.url),
}));

const LESSON_ID_ALIASES: Record<string, string> = {
  'lesson-01-01': 'hsk1-lesson-01',
  'lesson-01-02': 'hsk1-lesson-01',
  'lesson-01-03': 'hsk1-lesson-01',
  'day-01': 'hsk1-lesson-01',
  'day-02': 'hsk1-lesson-02',
  'day-03': 'hsk1-lesson-03',
  'day-04': 'hsk1-lesson-04',
  'day-05': 'hsk1-lesson-05',
};

export function normalizeLessonId(lessonId: string): string {
  return LESSON_ID_ALIASES[lessonId] || lessonId;
}

export function getAllCuratedMedia(): CuratedMediaItem[] {
  return CURATED_MEDIA_RESOURCES;
}

export function getMediaByLessonId(lessonId: string): CuratedMediaItem[] {
  const normalized = normalizeLessonId(lessonId);
  const directMatches = CURATED_MEDIA_RESOURCES.filter(
    (item) =>
      (item.relatedLessonIds && item.relatedLessonIds.includes(lessonId)) ||
      (item.relatedLessonIds && item.relatedLessonIds.includes(normalized))
  );

  if (directMatches.length > 0) {
    return directMatches;
  }

  // Fallback curated resources for HSK 3 - HSK 6 lessons so every lesson has supplementary media
  return CURATED_MEDIA_RESOURCES.filter((item) =>
    [
      'media-drive-hsk-standard',
      'media-drive-vocab-full',
      'media-drive-passive-audio',
      'media-read-xiaomin',
      'media-yt-everydaychinese',
      'media-drive-roadmap-12m',
    ].includes(item.id)
  );
}

export function getMediaByCategory(category: CuratedMediaCategory): CuratedMediaItem[] {
  return CURATED_MEDIA_RESOURCES.filter((item) => item.category === category);
}

export function getThematicFlashcardByLessonId(lessonId: string): ThematicFlashcardSet | undefined {
  const normalized = normalizeLessonId(lessonId);
  return THEMATIC_FLASHCARD_SETS.find(
    (set) => set.relatedLessonId === lessonId || set.relatedLessonId === normalized
  );
}
